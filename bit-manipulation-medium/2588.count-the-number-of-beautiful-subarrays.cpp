class Solution {
public:
  long long beautifulSubarrays(vector<int> &nums) {
    unordered_map<int, int> cnt;
    cnt[0] = 1;
    long long res = 0;
    int tmp = 0;
    for (auto num : nums) {
      tmp ^= num;
      res += cnt[tmp]++;
    }

    return res;
  }
};
